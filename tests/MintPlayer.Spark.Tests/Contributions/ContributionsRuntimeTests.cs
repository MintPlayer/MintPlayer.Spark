    // ---- rebuild --------------------------------------------------------------------------------------

    [Fact]
    public async Task RebuildCurrentAsync_repairs_hand_corrupted_current_documents()
    {
        var host = await StartAsync();
        await AddAsync(host, "en", "Latn", "alice's text");
        host.Identity.Id = Bob;
        await EditTextAsync(host, "en/Latn", "bob's text");

        await SeedAsync(async session =>
        {
            var current = await session.LoadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn"));
            current.Text = "corrupted";
            current.ContributorId = "users/nobody";
            await session.StoreAsync(new CoSongLyricsCurrent { TargetId = SongId, Language = "fr", Script = "Latn", Text = "orphan" }, CurrentId("fr", "Latn"));
        });

        using (var scope = host.Factory.CreateScope())
            await scope.ServiceProvider.GetRequiredService<IContributions>().RebuildCurrentAsync(SongId);

        var repaired = await ReadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn"));
        repaired!.Text.Should().Be("bob's text");
        repaired.ContributorId.Should().Be(Bob);
        repaired.ContributionCount.Should().Be(2);
        (await ReadAsync<CoSongLyricsCurrent>(CurrentId("fr", "Latn"))).Should().BeNull("no contribution backs it");
    }

    [Fact]
    public async Task A_changed_shape_rebuilds_every_target_at_startup()
    {
        // State left by an older shape: a contribution, a stale current, and a marker with another hash.
        await SeedAsync(async session =>
        {
            await session.StoreAsync(new CoSong { Title = "t" }, SongId);
            await session.StoreAsync(new CoSongLyricsContribution
            {
                TargetId = SongId, ContributorId = Alice, Language = "en", Script = "Latn", Text = "truth",
                UpdatedAt = new DateTime(2026, 1, 1, 0, 0, 0, DateTimeKind.Utc),
            }, ContributionId("en", "Latn", Alice));
            await session.StoreAsync(new CoSongLyricsCurrent { TargetId = SongId, Language = "en", Script = "Latn", Text = "stale" }, CurrentId("en", "Latn"));
            await session.StoreAsync(new ContributionShapeMarker { Shape = "0000000000000000" }, ContributionShapeMarker.IdFor(CoSongLyricsContributionMetadata.Instance));
        });

        await StartAsync(seedSong: false);

        var current = await ReadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn"));
        current!.Text.Should().Be("truth", "the startup check rebuilt the current documents of the changed declaration");
        current.ContributionCount.Should().Be(1);
        current.ContributionId.Should().Be(ContributionId("en", "Latn", Alice));
        (await ReadAsync<ContributionShapeMarker>(ContributionShapeMarker.IdFor(CoSongLyricsContributionMetadata.Instance)))!
            .Shape.Should().Be(CoSongLyricsContributionMetadata.Shape);

        // The marker now matches: a second start rebuilds nothing.
        await SeedAsync(async session => (await session.LoadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn"))).Text = "hand edit");
        await StartAsync(seedSong: false);
        (await ReadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn")))!.Text.Should().Be("hand edit");
    }

