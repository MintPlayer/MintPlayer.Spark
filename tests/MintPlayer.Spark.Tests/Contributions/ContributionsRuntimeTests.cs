/// <summary>Records the request session's request count around the contributions interceptor's hydration.</summary>
public sealed class CoProbe
{
    private readonly Dictionary<object, int> before = new(ReferenceEqualityComparer.Instance);
    public List<int> LoadDeltas { get; } = [];

    public void Clear()
    {
        lock (LoadDeltas) { before.Clear(); LoadDeltas.Clear(); }
    }

    public void Before(object entity, int requests)
    {
        lock (LoadDeltas) before[entity] = requests;
    }

    public void After(object entity, int requests)
    {
        lock (LoadDeltas)
            if (before.Remove(entity, out var start))
                LoadDeltas.Add(requests - start);
    }
}

