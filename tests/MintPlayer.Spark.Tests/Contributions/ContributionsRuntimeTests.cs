/// <summary>
/// Contributions M5a — the runtime against a real host and a real RavenDB, over HTTP: hydration (R2),
/// per-user writes that never touch the target document (R3) or another user's contribution (R4),
/// latest-wins current documents recomputed on withdraw, hide and restore (R5), the concurrency pin,
/// the owner's delete, the rebuild and the startup shape check.
/// </summary>
/// <remarks>
/// The types are generated by the real Contributions generator (<see cref="CoSong.Lyrics"/>): the test
/// project imports <c>spark-contributions.targets</c>. Fixture names start with <c>Co</c>, because the
/// actions resolver matches by simple name across the assembly.
