    // ---- R5: hide and restore -------------------------------------------------------------------------

    [Fact]
    public async Task Hiding_the_current_contribution_makes_the_previous_one_current_and_restoring_brings_it_back()
    {
        var host = await StartAsync();
        await AddAsync(host, "en", "Latn", "alice's text");
        host.Identity.Id = Bob;
        await EditTextAsync(host, "en/Latn", "bob's spam");

        // A moderator hides Bob's contribution: a soft delete through the contribution type's own PO.
        host.Identity.Id = "users/moderator";
        await host.Client.DeletePersistentObjectAsync(ContributionTypeId, ContributionId("en", "Latn", Bob));

        (await ReadAsync<CoSongLyricsContribution>(ContributionId("en", "Latn", Bob)))!.IsDeleted.Should().BeTrue();
        var current = await ReadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn"));
        current!.ContributorId.Should().Be(Alice, "the hide recomputes the current in the delete's own commit (R5, no index lag)");
        current.ContributionCount.Should().Be(1);
        TextOf(await LoadSongAsync(host), "en/Latn").Should().Be("alice's text");

        // A moderator's hide is not undone by the author saving the slot again.
        host.Identity.Id = Bob;
        var refused = await Assert.ThrowsAsync<SparkClientException>(() => EditTextAsync(host, "en/Latn", "bob again"));
        refused.StatusCode.Should().Be(HttpStatusCode.BadRequest);
        refused.ResponseBody.Should().Contain("hidden by a moderator");

        host.Identity.Id = "users/moderator";
        var response = await host.Client.SendAsync(HttpMethod.Post, "/spark/po/restore",
            JsonContent.Create(Wire.Typed(ContributionTypeId, id: ContributionId("en", "Latn", Bob))), requiresAntiforgery: true);
        response.StatusCode.Should().Be(HttpStatusCode.OK, await response.Content.ReadAsStringAsync());

        current = await ReadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn"));
        current!.ContributorId.Should().Be(Bob, "the restored contribution is the latest again");
        current.ContributionCount.Should().Be(2);
    }

    // ---- S-C4: two contributors racing ---------------------------------------------------------------

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task Two_contributors_racing_on_one_slot_lose_nothing(bool slotExists)
    {
        var host = await StartAsync();
        if (slotExists)
            await AddAsync(host, "en", "Latn", "first");
        var songBefore = await ChangeVectorAsync<CoSong>(SongId);

        host.Race.Arm(SongId);
        var ex = await Assert.ThrowsAsync<SparkClientException>(() => slotExists
            ? EditTextAsync(host, "en/Latn", "alice's edit")
            : AddAsync(host, "en", "Latn", "alice's edit"));

        host.Race.Fired.Should().BeTrue("Bob's save must have landed between Alice's read and her write");
        ex.StatusCode.Should().Be(HttpStatusCode.Conflict, "the current document is written with a pinned change vector; the client's conflict flow takes over");
        var current = await ReadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn"));
        current!.ContributorId.Should().Be(Bob, "Bob's concurrent version survives");
        current.Text.Should().Be("bob's concurrent text");
        var alices = await ReadAsync<CoSongLyricsContribution>(ContributionId("en", "Latn", Alice));
        if (slotExists)
            alices!.Text.Should().Be("first", "the refused save rolled back Alice's contribution with it (one transaction)");
        else
            alices.Should().BeNull("the refused save rolled back Alice's contribution with it (one transaction)");
        (await ChangeVectorAsync<CoSong>(SongId)).Should().Be(songBefore);

        // The retry the client makes after re-fetching succeeds.
        await EditTextAsync(host, "en/Latn", "alice's edit");
        (await ReadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn")))!.ContributorId.Should().Be(Alice);
    }

