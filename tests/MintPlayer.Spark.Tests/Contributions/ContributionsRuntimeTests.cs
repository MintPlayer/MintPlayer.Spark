    private static readonly Guid SongTypeId = Guid.Parse("c0d10000-0000-4000-8000-c0d100000001");
    private static readonly Guid LyricsTypeId = Guid.Parse("c0d10000-0000-4000-8000-c0d100000002");
    private static readonly Guid ContributionTypeId = Guid.Parse("c0d10000-0000-4000-8000-c0d100000003");
    private const string SongId = "CoSongs/1";
    private const string Alice = "users/alice";
    private const string Bob = "users/bob";

    private readonly List<IAsyncDisposable> factories = [];
    private readonly List<IDisposable> clients = [];

    public override async Task DisposeAsync()
    {
        foreach (var client in clients)
            client.Dispose();
        foreach (var factory in factories)
            await factory.DisposeAsync();
        await base.DisposeAsync();
    }

    private sealed record Host(SparkEndpointFactory Factory, SparkClient Client, CoIdentity Identity, CoProbe Probe, CoRace Race);

    private async Task<Host> StartAsync(Action<IServiceCollection>? services = null, bool seedSong = true)
    {
        if (seedSong)
            await SeedAsync(session => session.StoreAsync(new CoSong { Title = "Gangnam Style" }, SongId));

        var identity = new CoIdentity { Id = Alice };
        var probe = new CoProbe();
        var race = new CoRace(Store);
        var factory = new SparkEndpointFactory(
            Store,
            [SongModel(), LyricsModel(), ContributionModel()],
            configureServices: s =>
            {
                s.AddSingleton(identity);
                s.AddSingleton(probe);
                s.AddSingleton(race);
                s.AddScoped<ISparkCurrentUser, CoCurrentUser>();
                services?.Invoke(s);
            },
            configureSpark: spark =>
            {
                spark.AddSoftDelete();
                spark.AddContributions(typeof(CoSong).Assembly);
                spark.AddPersistentObjectInterceptor<CoProbeBefore>();
                spark.AddPersistentObjectInterceptor<CoProbeAfter>();
                spark.AddPersistentObjectInterceptor<CoRaceInterceptor>();
            });
        factories.Add(factory);
        var client = new SparkClient(factory.CreateClient(), ownsClient: true);
        clients.Add(client);
        return new Host(factory, client, identity, probe, race);
    }

    // ---- helpers --------------------------------------------------------------------------------------

    private static async Task<PO> LoadSongAsync(Host host)
        => await host.Client.GetPersistentObjectAsync(SongTypeId, SongId) ?? throw new InvalidOperationException("song not visible");

    private static PersistentObjectAttributeAsDetail Lyrics(PO po) => (PersistentObjectAttributeAsDetail)po["Lyrics"];

    private static PO NewRow(string language, string script, string text, params (string Name, object Value)[] extra) => new()
    {
        Name = "CoLyrics",
        ObjectTypeId = LyricsTypeId,
        Attributes =
        [
            new PersistentObjectAttribute { Name = "Language", DataType = "string", Value = language, IsValueChanged = true },
            new PersistentObjectAttribute { Name = "Script", DataType = "string", Value = script, IsValueChanged = true },
            new PersistentObjectAttribute { Name = "Text", DataType = "string", Value = text, IsValueChanged = true },
            .. extra.Select(e => new PersistentObjectAttribute { Name = e.Name, DataType = "string", Value = e.Value, IsValueChanged = true }),
        ],
    };

    /// <summary>Replaces the song's rows with <paramref name="rows"/> and saves as the current identity.</summary>
    private static async Task<PO> SaveRowsAsync(Host host, Func<List<PO>, List<PO>> edit)
    {
        var po = await LoadSongAsync(host);
        var lyrics = Lyrics(po);
        lyrics.Objects = edit([.. lyrics.Objects ?? []]);
        lyrics.IsValueChanged = true;
        return await host.Client.UpdatePersistentObjectAsync(po);
    }

    private static Task<PO> AddAsync(Host host, string language, string script, string text)
        => SaveRowsAsync(host, rows => [.. rows, NewRow(language, script, text)]);

    private static Task<PO> EditTextAsync(Host host, string key, string text) => SaveRowsAsync(host, rows =>
    {
        var row = rows.Single(r => r.Id == key);
        row["Text"].Value = text;
        row["Text"].IsValueChanged = true;
        return rows;
    });

    private static Task<PO> RemoveAsync(Host host, string key) => SaveRowsAsync(host, rows => [.. rows.Where(r => r.Id != key)]);

    private async Task<T?> ReadAsync<T>(string id) where T : class
    {
        using var session = Store.OpenAsyncSession();
        return await session.LoadAsync<T>(id);
    }

    private async Task<string?> ChangeVectorAsync<T>(string id) where T : class
    {
        using var session = Store.OpenAsyncSession();
        var doc = await session.LoadAsync<T>(id);
        return doc is null ? null : session.Advanced.GetChangeVectorFor(doc);
    }

    private static string ContributionId(string language, string script, string user) => CoSongLyricsContribution.GetId(SongId, language, script, user);
    private static string CurrentId(string language, string script) => CoSongLyricsCurrent.GetId(SongId, language, script);

    private async Task<IReadOnlyList<string>> IdsStartingWithAsync(string prefix)
    {
        using var session = Store.OpenAsyncSession();
        var docs = await session.Advanced.LoadStartingWithAsync<object>(prefix, pageSize: 1024);
        return [.. docs.Select(d => session.Advanced.GetDocumentId(d))];
    }

    private static string TextOf(PO po, string key) => Lyrics(po).Objects!.Single(r => r.Id == key)["Text"].Value?.ToString() ?? "";

    // ---- R2: hydration -------------------------------------------------------------------------------

    [Fact]
    public async Task Loading_a_song_shows_the_current_versions_with_one_request_for_all_of_them()
    {
        var host = await StartAsync();
        await AddAsync(host, "ko", "Kore", "오빤 강남스타일");
        await AddAsync(host, "ko", "Latn", "oppan gangnam style");
        host.Probe.Clear();

        var po = await LoadSongAsync(host);

        Lyrics(po).Objects!.Select(r => r.Id).Should().BeEquivalentTo(["ko/Kore", "ko/Latn"]);
        TextOf(po, "ko/Latn").Should().Be("oppan gangnam style");
        host.Probe.LoadDeltas.Should().NotBeEmpty("the GET materializes the song");
        host.Probe.LoadDeltas.Should().AllSatisfy(delta => delta.Should().Be(1, "all current versions arrive in one lazy prefix request (R2, S-C6)"));
    }

    // ---- R3: the target is never written ---------------------------------------------------------------

    [Fact]
    public async Task Adding_a_version_writes_my_contribution_and_the_current_document_and_never_the_song()
    {
        var host = await StartAsync();
        var songBefore = await ChangeVectorAsync<CoSong>(SongId);

        await AddAsync(host, "en", "Latn", "Oppa is Gangnam style");

        (await ChangeVectorAsync<CoSong>(SongId)).Should().Be(songBefore, "only contributions changed, so the song document is not rewritten (R3)");
        var mine = await ReadAsync<CoSongLyricsContribution>(ContributionId("en", "Latn", Alice));
        mine.Should().NotBeNull();
        mine!.ContributorId.Should().Be(Alice);
        mine.Text.Should().Be("Oppa is Gangnam style");
        var current = await ReadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn"));
        current!.ContributorId.Should().Be(Alice);
        current.ContributionId.Should().Be(ContributionId("en", "Latn", Alice));
        current.Text.Should().Be("Oppa is Gangnam style");
        current.ContributionCount.Should().Be(1);
    }

    [Fact]
    public async Task A_save_that_changes_no_row_writes_nothing()
    {
        var host = await StartAsync();
        await AddAsync(host, "en", "Latn", "same");
        var contribution = await ChangeVectorAsync<CoSongLyricsContribution>(ContributionId("en", "Latn", Alice));
        var current = await ChangeVectorAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn"));

        var po = await LoadSongAsync(host);
        po["Title"].Value = "Gangnam Style (2012)";
        po["Title"].IsValueChanged = true;
        Lyrics(po).IsValueChanged = true;
        await host.Client.UpdatePersistentObjectAsync(po);

        (await ReadAsync<CoSong>(SongId))!.Title.Should().Be("Gangnam Style (2012)");
        (await ChangeVectorAsync<CoSongLyricsContribution>(ContributionId("en", "Latn", Alice))).Should().Be(contribution);
        (await ChangeVectorAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn"))).Should().Be(current);
    }

    // ---- R4: owner-only --------------------------------------------------------------------------------

    [Fact]
    public async Task Editing_someone_elses_version_writes_only_my_own_contribution_and_tampering_changes_nothing()
    {
        var host = await StartAsync();
        await AddAsync(host, "en", "Latn", "alice's text");
        var alicesBefore = await ChangeVectorAsync<CoSongLyricsContribution>(ContributionId("en", "Latn", Alice));

        host.Identity.Id = Bob;
        await SaveRowsAsync(host, rows =>
        {
            var row = rows.Single(r => r.Id == "en/Latn");
            row["Text"].Value = "bob's correction";
            row["Text"].IsValueChanged = true;
            // Tampering: who wrote it, and a forged contributor/user id. None of these is a writable row attribute.
            var tampered = new PO
            {
                Id = row.Id,
                Name = row.Name,
                ObjectTypeId = row.ObjectTypeId,
                Attributes = [.. row.Attributes,
                    new PersistentObjectAttribute { Name = "ContributorId", DataType = "string", Value = Alice, IsValueChanged = true },
                    new PersistentObjectAttribute { Name = "ContributorName", DataType = "string", Value = "Alice", IsValueChanged = true },
                    new PersistentObjectAttribute { Name = "UserId", DataType = "string", Value = Alice, IsValueChanged = true }],
            };
            return [.. rows.Select(r => r.Id == "en/Latn" ? tampered : r)];
        });

        (await ChangeVectorAsync<CoSongLyricsContribution>(ContributionId("en", "Latn", Alice))).Should().Be(alicesBefore, "Alice's contribution is never touched by Bob (R4)");
        (await ReadAsync<CoSongLyricsContribution>(ContributionId("en", "Latn", Alice)))!.Text.Should().Be("alice's text");
        var bobs = await ReadAsync<CoSongLyricsContribution>(ContributionId("en", "Latn", Bob));
        bobs!.ContributorId.Should().Be(Bob, "the contributor is the caller, whatever was posted");
        bobs.Text.Should().Be("bob's correction");
        var current = await ReadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn"));
        current!.ContributorId.Should().Be(Bob);
        current.ContributionCount.Should().Be(2);
        (await IdsStartingWithAsync(SongId + "/LyricsContributions/")).Should().HaveCount(2);
    }

    // ---- Q3: withdraw ---------------------------------------------------------------------------------

    [Fact]
    public async Task Removing_a_row_withdraws_only_my_contribution_and_the_previous_version_becomes_current()
    {
        var host = await StartAsync();
        await AddAsync(host, "en", "Latn", "alice's text");
        host.Identity.Id = Bob;
        await EditTextAsync(host, "en/Latn", "bob's text");

        var saved = await RemoveAsync(host, "en/Latn");

        var bobs = await ReadAsync<CoSongLyricsContribution>(ContributionId("en", "Latn", Bob));
        bobs!.IsDeleted.Should().BeTrue("a withdrawal soft-deletes the caller's own contribution");
        bobs.DeletedBy.Should().Be(Bob);
        (await ReadAsync<CoSongLyricsContribution>(ContributionId("en", "Latn", Alice)))!.IsDeleted.Should().BeFalse();
        var current = await ReadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn"));
        current!.ContributorId.Should().Be(Alice, "the latest visible contribution is current again");
        current.Text.Should().Be("alice's text");
        current.ContributionCount.Should().Be(1);
        TextOf(saved, "en/Latn").Should().Be("alice's text", "the save response shows the version that is current now");

        // Removing a row that shows only someone else's version withdraws nothing.
        await RemoveAsync(host, "en/Latn");
        (await ReadAsync<CoSongLyricsCurrent>(CurrentId("en", "Latn")))!.ContributorId.Should().Be(Alice);
        (await ReadAsync<CoSongLyricsContribution>(ContributionId("en", "Latn", Alice)))!.IsDeleted.Should().BeFalse();
    }

    [Fact]
    public async Task Withdrawing_the_only_version_deletes_the_current_document_and_saving_again_revives_it()
    {
        var host = await StartAsync();
