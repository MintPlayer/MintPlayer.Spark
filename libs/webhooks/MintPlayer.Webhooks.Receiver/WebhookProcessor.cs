using System;
using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;

namespace MintPlayer.Webhooks;

/// <summary>One verified delivery, handed to a <see cref="WebhookProcessor"/>.</summary>
public sealed class WebhookContext
{
    public WebhookContext(string messageId, long timestamp, WebhookEnvelope envelope, Func<string, string?> getHeader)
    {
        MessageId = messageId;
        Timestamp = timestamp;
        Envelope = envelope;
        GetHeader = getHeader;
    }

    /// <summary><c>webhook-id</c>: the same on every retry and redelivery. Deduplicate on it.</summary>
    public string MessageId { get; }

    /// <summary><c>webhook-timestamp</c> of this attempt (unix seconds).</summary>
    public long Timestamp { get; }

    public WebhookEnvelope Envelope { get; }

    public string Type => Envelope.Type;

    public JsonElement Data => Envelope.Data;

    /// <summary>Any request header, e.g. the producer's own <c>webhook-installation-id</c>.</summary>
    public Func<string, string?> GetHeader { get; }
}

/// <summary>
/// Routes verified events to handlers. Override <see cref="OnEventAsync"/> for untyped handling; a processor
/// generated by <c>spark webhooks generate</c> overrides <see cref="DispatchAsync"/> with one typed method per event.
/// </summary>
public abstract class WebhookProcessor
{
    /// <summary>The <c>ping</c> event a producer sends when an endpoint is created or changed.</summary>
    public const string PingEventType = "ping";

    /// <summary>The options event data is read with. Must match the producer's (see <see cref="WebhookJson"/>).</summary>
    protected virtual JsonSerializerOptions SerializerOptions => WebhookJson.Options;

    public Task ProcessAsync(WebhookContext context, CancellationToken cancellationToken)
        => context.Type == PingEventType ? OnPingAsync(context, cancellationToken) : DispatchAsync(context, cancellationToken);

    /// <summary>Picks the handler for <see cref="WebhookContext.Type"/>. The default sends everything to <see cref="OnEventAsync"/>.</summary>
    protected virtual Task DispatchAsync(WebhookContext context, CancellationToken cancellationToken) => OnEventAsync(context, cancellationToken);

    /// <summary>Every event no typed handler took. Default: ignore it (a 2xx, so the producer does not retry).</summary>
    protected virtual Task OnEventAsync(WebhookContext context, CancellationToken cancellationToken) => Task.CompletedTask;

    protected virtual Task OnPingAsync(WebhookContext context, CancellationToken cancellationToken) => Task.CompletedTask;

    /// <summary>The event data as <typeparamref name="T"/>.</summary>
    protected T Deserialize<T>(WebhookContext context)
        => context.Data.Deserialize<T>(SerializerOptions) ?? throw new JsonException($"Event '{context.Type}' has no data.");
}
