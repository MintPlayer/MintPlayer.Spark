using System.Text;

namespace MintPlayer.Spark.Cli.Webhooks;

/// <summary>What <c>spark webhooks generate</c> writes, besides the language.</summary>
/// <param name="Name">The processor's base name, e.g. <c>Coverage</c> → <c>CoverageWebhooksProcessor</c> / <c>CoverageWebhookEvents</c>.</param>
/// <param name="Namespace">C# only.</param>
public sealed record WebhookCodeOptions(string Name, string Namespace);

/// <summary>
/// C#: one class per object type, one enum per string enum, and an abstract <c>{Name}WebhooksProcessor</c> over
/// MintPlayer.Webhooks.Receiver's <c>WebhookProcessor</c> with a virtual <c>On{Event}Async</c> per event and the
/// <c>EventTypes</c> map MintPlayer.Spark.Webhooks.Receiver takes. It compiles on netstandard2.0 (no records, no init).
/// </summary>
public static class CSharpWebhookEmitter
{
    public static string Emit(WebhookCatalogModel model, WebhookCodeOptions options)
    {
        var processor = options.Name + "WebhooksProcessor";
        var w = new StringBuilder();
        w.AppendLine("// <auto-generated>");
        w.AppendLine($"// Generated by `spark webhooks generate` from \"{model.Title}\" {model.Version}. Regenerate it; do not edit.");
        w.AppendLine("// </auto-generated>");
        w.AppendLine("#nullable enable");
        w.AppendLine("using System;");
        w.AppendLine("using System.Collections.Generic;");
        w.AppendLine("using System.Text.Json;");
        w.AppendLine("using System.Text.Json.Serialization;");
        w.AppendLine("using System.Threading;");
        w.AppendLine("using System.Threading.Tasks;");
        w.AppendLine("using MintPlayer.Webhooks;");
        w.AppendLine();
        w.AppendLine($"namespace {options.Namespace};");

        foreach (var type in model.Types)
        {
            w.AppendLine();
            Summary(w, "", type.Description);
            if (type is WebhookEnumType enumType)
            {
                w.AppendLine($"public enum {type.Name}");
                w.AppendLine("{");
                foreach (var (wire, member) in enumType.Values)
                    w.AppendLine($"    /// <summary><c>{Xml(wire)}</c></summary>").AppendLine($"    {member},");
                w.AppendLine("}");
                continue;
            }

            var objectType = (WebhookObjectType)type;
            w.AppendLine($"public sealed partial class {type.Name}");
            w.AppendLine("{");
            var first = true;
            foreach (var property in objectType.Properties)
            {
                if (!first) w.AppendLine();
                first = false;
                Summary(w, "    ", property.Description);
                var csType = TypeName(property.Type);
                var initializer = property.Type.Nullable || IsValueType(property.Type, model) ? "" : " = default!;";
                w.AppendLine($"    [JsonPropertyName(\"{Escape(property.WireName)}\")]");
                w.AppendLine($"    public {csType} {property.Name} {{ get; set; }}{initializer}");
            }
            w.AppendLine("}");
        }

        w.AppendLine();
        w.AppendLine($"/// <summary>The events of \"{Xml(model.Title)}\". Override the <c>On…Async</c> methods you handle; the rest are acknowledged and ignored.</summary>");
        w.AppendLine($"public abstract class {processor} : WebhookProcessor");
        w.AppendLine("{");
        w.AppendLine("    /// <summary>Event type → data type, for MintPlayer.Spark.Webhooks.Receiver (<c>spark.AddWebhookReceiver(path, EventTypes, …)</c>).</summary>");
        w.AppendLine("    public static IReadOnlyDictionary<string, Type> EventTypes { get; } = new Dictionary<string, Type>(StringComparer.Ordinal)");
        w.AppendLine("    {");
        foreach (var e in model.Events)
            w.AppendLine($"        [\"{Escape(e.Name)}\"] = typeof({DataType(e)}),");
        w.AppendLine("    };");
        w.AppendLine();
        foreach (var e in model.Events)
            w.AppendLine($"    public const string {e.MethodName}Event = \"{Escape(e.Name)}\";");
        w.AppendLine();
        w.AppendLine("    protected override Task DispatchAsync(WebhookContext context, CancellationToken cancellationToken)");
        w.AppendLine("    {");
        w.AppendLine("        switch (context.Type)");
        w.AppendLine("        {");
        foreach (var e in model.Events)
            w.AppendLine($"            case {e.MethodName}Event: return On{e.MethodName}Async(Deserialize<{DataType(e)}>(context), context, cancellationToken);");
        w.AppendLine("            default: return OnEventAsync(context, cancellationToken);");
        w.AppendLine("        }");
        w.AppendLine("    }");
        foreach (var e in model.Events)
        {
            w.AppendLine();
            var summary = e.Summary is null ? "." : ": " + Xml(e.Summary);
            w.AppendLine($"    /// <summary><c>{Xml(e.Name)}</c>{summary}{(e.Permission is null ? "" : $" Needs <c>{Xml(e.Permission)}</c>.")}</summary>");
            w.AppendLine($"    protected virtual Task On{e.MethodName}Async({DataType(e)} data, WebhookContext context, CancellationToken cancellationToken) => Task.CompletedTask;");
        }
        w.AppendLine("}");
        return w.ToString();
    }

    private static string DataType(WebhookEventModel e) => e.Data is WebhookNamed named ? named.Name : TypeName(e.Data with { Nullable = false });

    private static string TypeName(WebhookTypeRef type)
    {
        var name = type switch
        {
            WebhookPrimitive { Kind: "string", Format: "date-time" } => "DateTimeOffset",
            WebhookPrimitive { Kind: "string", Format: "uuid" } => "Guid",
            WebhookPrimitive { Kind: "string" } => "string",
            WebhookPrimitive { Kind: "integer" } => "long",
            // decimal: event data is mostly money and rates, where a double's rounding shows.
            WebhookPrimitive { Kind: "number" } => "decimal",
            WebhookPrimitive { Kind: "boolean" } => "bool",
            WebhookArray array => $"List<{TypeName(array.Item)}>",
            WebhookMap map => $"Dictionary<string, {TypeName(map.Value)}>",
            WebhookNamed named => named.Name,
            _ => "JsonElement",
        };
        return type.Nullable ? name + "?" : name;
    }

    private static bool IsValueType(WebhookTypeRef type, WebhookCatalogModel model) => type switch
    {
        WebhookPrimitive { Kind: "string", Format: "date-time" or "uuid" } => true,
        WebhookPrimitive { Kind: "string" } => false,
        WebhookPrimitive => true,
        WebhookNamed named => model.Types.Any(t => t.Name == named.Name && t is WebhookEnumType),
        WebhookAny => true,
        _ => false,
    };

    private static void Summary(StringBuilder w, string indent, string? text)
    {
        if (!string.IsNullOrWhiteSpace(text))
            w.AppendLine($"{indent}/// <summary>{Xml(text)}</summary>");
    }

    private static string Xml(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\r", "").Replace("\n", " ");

    private static string Escape(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"");
}

/// <summary>
/// TypeScript: an interface per object type (wire names, so the parsed JSON is the type), a union per enum, and
/// <c>{Name}WebhookEvents</c>, the event → data map <c>@mintplayer/webhooks-receiver</c>'s <c>createWebhookReceiver</c> takes.
/// </summary>
public static class TypeScriptWebhookEmitter
{
    public static string Emit(WebhookCatalogModel model, WebhookCodeOptions options)
    {
        var w = new StringBuilder();
        w.AppendLine($"// Generated by `spark webhooks generate` from \"{model.Title}\" {model.Version}. Regenerate it; do not edit.");
        foreach (var type in model.Types)
        {
            w.AppendLine();
            Doc(w, "", type.Description);
            if (type is WebhookEnumType enumType)
            {
                w.AppendLine($"export type {type.Name} = {string.Join(" | ", enumType.Values.Select(v => Quote(v.Wire)))};");
                continue;
            }
            w.AppendLine($"export interface {type.Name} {{");
            foreach (var property in ((WebhookObjectType)type).Properties)
            {
                Doc(w, "  ", property.Description);
                w.AppendLine($"  {Key(property.WireName)}: {TypeName(property.Type)};");
            }
            w.AppendLine("}");
        }

        w.AppendLine();
        w.AppendLine($"/** The events of \"{model.Title}\": event type → the type of its `data`. */");
        w.AppendLine($"export interface {options.Name}WebhookEvents {{");
        foreach (var e in model.Events)
        {
            Doc(w, "  ", string.Join(" ", new[] { e.Summary, e.Permission is null ? null : $"Needs `{e.Permission}`." }.Where(s => s is not null)));
            w.AppendLine($"  {Quote(e.Name)}: {TypeName(e.Data with { Nullable = false })};");
        }
        w.AppendLine("}");
        w.AppendLine();
        var constant = char.ToLowerInvariant(options.Name[0]) + options.Name[1..] + "WebhookEventTypes";
        w.AppendLine($"export const {constant} = [{string.Join(", ", model.Events.Select(e => Quote(e.Name)))}] as const;");
        return w.ToString();
    }

    private static string TypeName(WebhookTypeRef type)
    {
        var name = type switch
        {
            WebhookPrimitive { Kind: "string" } => "string",
            WebhookPrimitive { Kind: "integer" or "number" } => "number",
            WebhookPrimitive { Kind: "boolean" } => "boolean",
            WebhookArray array => array.Item.Nullable ? $"({TypeName(array.Item)})[]" : $"{TypeName(array.Item)}[]",
            WebhookMap map => $"Record<string, {TypeName(map.Value)}>",
            WebhookNamed named => named.Name,
            _ => "unknown",
        };
        return type.Nullable && name != "unknown" ? name + " | null" : name;
    }

    private static void Doc(StringBuilder w, string indent, string? text)
    {
        if (!string.IsNullOrWhiteSpace(text))
            w.AppendLine($"{indent}/** {text.Replace("*/", "*\\/").Replace("\r", "").Replace("\n", " ")} */");
    }

    private static string Key(string name) => IsIdentifier(name) ? name : Quote(name);

    private static bool IsIdentifier(string name)
        => name.Length > 0 && (char.IsAsciiLetter(name[0]) || name[0] is '_' or '$') && name.All(c => char.IsAsciiLetterOrDigit(c) || c is '_' or '$');

    private static string Quote(string text) => "'" + text.Replace("\\", "\\\\").Replace("'", "\\'") + "'";
}
