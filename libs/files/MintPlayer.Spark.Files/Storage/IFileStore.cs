namespace MintPlayer.Spark.Files.Storage;

/// <summary>
/// Where a browser sends a file's bytes directly, bypassing Spark.
/// </summary>
/// <param name="Url">Where to send them.</param>
/// <param name="Method"><c>POST</c>: a multipart form of <paramref name="Fields"/>, in order, then the file as <c>file</c> (an S3 POST policy).
/// <c>PUT</c>: the raw bytes as the body, with <paramref name="Headers"/> (an Azure SAS).</param>
/// <param name="Fields">The form fields of a <c>POST</c>.</param>
/// <param name="Headers">The request headers of a <c>PUT</c>.</param>
public sealed record SparkFileUploadTarget(string Url, string Method, IReadOnlyDictionary<string, string> Fields, IReadOnlyDictionary<string, string> Headers)
{
    public const string Post = "POST";
    public const string Put = "PUT";
}

/// <summary>
/// What a direct read URL must make the store's server answer with (#700 §3.5): the sniffed type, the sanitised name and the
/// disposition Files decided, and an expiry. <see cref="ContentDisposition"/> is the complete header value.
/// </summary>
public sealed record SparkFileReadRequest(string ContentType, string ContentDisposition, DateTimeOffset Expires);

/// <summary>An object a store holds, as its listing reports it (for the orphan reconcile).</summary>
public sealed record SparkStoredObject(string Key, DateTimeOffset LastModified);

/// <summary>
/// Where file bytes live (#700 D12). Keys are generated by the server, never derived from a client's file name; a store
/// must refuse a key it did not make (no traversal, no other app's prefix).
/// </summary>
/// <remarks>
/// One store per app. <c>AddFiles()</c> registers RavenDB attachments; <c>Files.FileSystem</c>, <c>Files.AzureBlob</c> and
/// <c>Files.S3</c> replace it (<see cref="ObjectFileStore"/>). Every store passes the same conformance suite.
/// <para>
/// A store either joins the save's unit of work (<see cref="ISessionFileStore"/>: RavenDB attachments), or it does not, and
/// then Files drives it around the commit: a claimed upload is copied to its entity key before the commit, files the saved
/// entity no longer holds are deleted after it, and <see cref="ListAsync"/> lets the reconcile sweep remove what a failure in
/// between left behind.
/// </para>
/// </remarks>
public interface IFileStore
{
    /// <summary>
    /// A direct upload target for the staged object <paramref name="key"/>, capped at <paramref name="maxBytes"/> where
    /// the store can enforce it, or null when the bytes go through Spark's upload endpoint.
    /// </summary>
    Task<SparkFileUploadTarget?> CreateUploadTargetAsync(string key, long maxBytes, DateTimeOffset expires, CancellationToken cancellationToken);

    /// <summary>Writes <paramref name="content"/> under <paramref name="key"/>, streamed.</summary>
    Task WriteAsync(string key, Stream content, string? contentType, CancellationToken cancellationToken);

    /// <summary>
    /// A presigned URL a browser reads <paramref name="key"/> from directly until <see cref="SparkFileReadRequest.Expires"/>,
    /// answering with the request's type and disposition, or null when the store's bytes are proxied through Spark. Signed
    /// locally: no round trip, so a read response can embed one per file (D15). Called only after Files checked the read.
    /// </summary>
    Uri? CreateReadUrl(string key, SparkFileReadRequest request);

    /// <summary>Opens the bytes under <paramref name="key"/>, or null when there are none. The caller disposes the stream.</summary>
    Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken);

    /// <summary>Deletes the bytes under <paramref name="key"/>; a missing key is not an error.</summary>
    Task DeleteAsync(string key, CancellationToken cancellationToken);

    /// <summary>Copies the bytes under <paramref name="sourceKey"/> to <paramref name="destinationKey"/>, replacing what is there.</summary>
    Task CopyAsync(string sourceKey, string destinationKey, CancellationToken cancellationToken);

    /// <summary>The objects under <paramref name="prefix"/> (a key prefix this store made), for the orphan reconcile.</summary>
    IAsyncEnumerable<SparkStoredObject> ListAsync(string prefix, CancellationToken cancellationToken);

    /// <summary>The key an upload's bytes are staged under.</summary>
    string StagingKey(string token);

    /// <summary>The key an upload's image variant <paramref name="variant"/> is staged under, next to the original (M8).</summary>
    string StagingVariantKey(string token, string variant);

    /// <summary>
    /// The key of the file <paramref name="fileId"/> that the entity <paramref name="entityId"/> holds. An image variant's file
    /// id is <c>{fileId}.{variant}</c> (<see cref="SparkFileKeys.VariantFileId"/>), so it shares the file's prefix and
    /// <see cref="EraseAsync"/> finds it.
    /// </summary>
    string EntityKey(string entityId, string fileId);

    /// <summary>The key prefix every object of the entity <paramref name="entityId"/> starts with: its files and their variants.</summary>
    string EntityPrefix(string entityId);

    /// <summary>
    /// Erases the file <paramref name="fileId"/> of <paramref name="entityId"/> beyond recovery, with its variants (#700 SP8): the
    /// explicit erasure hook for an app's GDPR flow, never called by Files itself. A replaced or cleared file stays readable from
    /// history on the RavenDB store (a revision keeps its attachment), so this also deletes the entity's revisions that still hold
    /// it. An external store keeps no copy per revision; deleting the objects is enough. Clear the attribute (or delete the
    /// entity) first: an entity still holding the file would point at nothing.
    /// </summary>
    Task EraseAsync(string entityId, string fileId, CancellationToken cancellationToken);
}

/// <summary>
/// A store whose writes join the save's RavenDB session, so files appear and disappear exactly when the entity commits and a
/// refused save leaves them untouched. Files calls these instead of copying before and deleting after the commit.
/// </summary>
public interface ISessionFileStore : IFileStore
{
    /// <summary>Within a save, after the entity was stored and before the commit: makes the staged bytes the entity's file.</summary>
    Task AttachAsync(SparkFileTransfer transfer, CancellationToken cancellationToken);

    /// <summary>Within a save: removes the entity's file, which the saved value no longer holds.</summary>
    Task DetachAsync(SparkFileTransfer transfer, CancellationToken cancellationToken);
}

/// <summary>One file moving into or out of an entity during a save.</summary>
/// <param name="Session">The save's session, not yet committed.</param>
/// <param name="EntityId">The entity's document id.</param>
/// <param name="FileId">The server-generated file id (<see cref="Abstractions.SparkFile.FileId"/>).</param>
/// <param name="StagingKey">Where the claimed upload's bytes are staged; null for a detach.</param>
public sealed record SparkFileTransfer(Abstractions.Storage.ISparkSession Session, string EntityId, string FileId, string? StagingKey);
