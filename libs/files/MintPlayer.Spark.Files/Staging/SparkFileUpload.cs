using MintPlayer.Spark.Abstractions;

namespace MintPlayer.Spark.Files.Staging;

/// <summary>Where an upload is in its life (#700 D3).</summary>
public enum SparkFileUploadState
{
    /// <summary>A slot was issued; no bytes yet.</summary>
    Prepared,
    /// <summary>Bytes arrived through Spark; not yet checked.</summary>
    Uploaded,
    /// <summary>Sniffed, sized, validated and scanned: a save can claim it when its scan status is <c>Clean</c>.</summary>
    Committed,
    /// <summary>Refused at commit; its bytes are deleted.</summary>
    Refused,
    /// <summary>A save took it. A claimed upload is never claimed again.</summary>
    Claimed,
}

/// <summary>
/// A staged upload: the document behind an upload token (<c>SparkFileUploads/{token}</c>). It is bound to the user, the
/// entity type, the attribute and (for an edit) the object, and it expires (<see cref="IExpiring"/>), taking its bytes
/// with it on every store (the RavenDB store keeps them as its attachment; the others are reconciled).
/// </summary>
public sealed class SparkFileUpload : IExpiring
{
    public const string CollectionPrefix = "SparkFileUploads/";

    public static string IdFor(string token) => CollectionPrefix + token;

    public string? Id { get; set; }

    public string Token { get; set; } = string.Empty;

    public string UserId { get; set; } = string.Empty;

    public Guid EntityTypeId { get; set; }

    public string Attribute { get; set; } = string.Empty;

    /// <summary>The object being edited, or null for a create.</summary>
    public string? ObjectId { get; set; }

    public string DataType { get; set; } = SparkFileDataTypes.BinaryFile;

    public SparkFileUploadState State { get; set; }

    /// <summary>The sanitised display name.</summary>
    public string FileName { get; set; } = string.Empty;

    /// <summary>What the client said the size was, refused up front when over <see cref="MaxBytes"/>; never trusted after.</summary>
    public long DeclaredLength { get; set; }

    /// <summary>The cap in force when the slot was issued: the attribute's, else the global.</summary>
    public long MaxBytes { get; set; }

    /// <summary>The store key of the staged bytes, generated by the server.</summary>
    public string StagingKey { get; set; } = string.Empty;

    /// <summary>The bytes may arrive until then.</summary>
    public DateTime UploadDeadlineUtc { get; set; }

    // ---- set at commit ----

    public string? ContentType { get; set; }

    public long Length { get; set; }

    public string? Sha256 { get; set; }

    public SparkFileScanStatus ScanStatus { get; set; } = SparkFileScanStatus.Pending;

    public int? Width { get; set; }

    public int? Height { get; set; }

    /// <summary>
    /// The image processor has replaced the staged bytes with its re-encoding (M8). A retried commit then neither re-encodes
    /// them again nor re-sniffs them against the accept list (a GIF is a PNG by now).
    /// </summary>
    public bool ImageProcessed { get; set; }

    /// <summary>Generated variants by name, their bytes staged next to the original. Their <c>FileId</c> is set by the claim.</summary>
    public Dictionary<string, SparkImageVariant>? Variants { get; set; }

    /// <summary>Why the commit refused the file, shown to the uploader.</summary>
    public string? Error { get; set; }

    public DateTime CreatedAtUtc { get; set; }

    public DateTime? ExpiresAtUtc { get; set; }
}
