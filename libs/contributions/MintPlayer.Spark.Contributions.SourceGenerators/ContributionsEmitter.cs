    private const string Format = "global::MintPlayer.Spark.Contributions.ContributionSlotFormat";
    private const string HasNaturalId = "global::MintPlayer.Spark.Abstractions.IHasNaturalId";
    private const string Header = "// <auto-generated by MintPlayer.Spark.Contributions.SourceGenerators />\n#nullable enable\n";

    // ------------------------------------------------------------------ per declaration

    public static string Declaration(ContributionModel m)
    {
        var w = new Writer();
        w.Raw(Header);
        var access = m.IsPublic ? "public" : "internal";
        var ns = !string.IsNullOrEmpty(m.Namespace);
        if (ns) w.Open($"namespace {m.Namespace}");

        WriteContribution(w, m, access);
        w.Line();
        WriteCurrent(w, m, access);
        w.Line();
        WriteMetadata(w, m, access);

        if (ns) w.Close();
        return w.ToString();
    }

    private static void WriteContribution(Writer w, ContributionModel m, string access)
    {
        var interfaces = $"global::MintPlayer.Spark.Contributions.IContribution, {HasNaturalId}";
        if (m.IsSoftDeletable && m.EmitSoftDeleteMembers)
            interfaces += ", global::MintPlayer.Spark.SoftDelete.ISoftDeletable";

        w.Line("/// <summary>");
        w.Line($"/// One user's contribution to <see cref=\"{m.OwnerType}.{m.PropertyName}\"/>{(m.IsCollection ? " for one slot" : "")}. Id:");
        w.Line($"/// <c>{{targetId}}/{m.PropertyName}Contributions/{SlotPath(m)}User/{{userId}}</c>.");
        w.Line("/// </summary>");
        w.Line("/// <remarks>");
        w.Line("/// Generated by MintPlayer.Spark.Contributions; <c>partial</c>, so the app can add <c>IModeratable</c>.");
        w.Line("/// The type name is a RavenDB collection name and a <c>security.json</c> resource: renaming the");
        w.Line("/// target or the property means migrating both.");
        w.Line("/// </remarks>");
        w.Line("[global::System.CodeDom.Compiler.GeneratedCode(\"MintPlayer.Spark.Contributions.SourceGenerators\", \"1\")]");
        w.Open($"{access} partial class {m.ContributionName} : {interfaces}");

        w.Line("/// <summary>The document id; see <see cref=\"GetId\"/>.</summary>");
        w.Line("public string? Id { get; set; }");
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Line("public string TargetId { get; set; } = \"\";");
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Line("public string ContributorId { get; set; } = \"\";");
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Line("public global::System.DateTime UpdatedAt { get; set; }");
        WriteSlotAndValueProperties(w, m);

        if (m.IsSoftDeletable && m.EmitSoftDeleteMembers)
        {
            w.Line();
            w.Line("/// <inheritdoc />");
            w.Line("public bool IsDeleted { get; set; }");
            w.Line();
            w.Line("/// <inheritdoc />");
            w.Line("public global::System.DateTimeOffset? DeletedAt { get; set; }");
            w.Line();
            w.Line("/// <inheritdoc />");
            w.Line("public string? DeletedBy { get; set; }");
            w.Line();
            w.Line("/// <inheritdoc />");
            w.Line("public string? DeleteReason { get; set; }");
        }

        w.Line();
        w.Line($"/// <summary><c>{{targetId}}/{m.PropertyName}Contributions/{SlotPath(m)}User/{{userId}}</c>; the user id keeps its own slashes.</summary>");
        var parameters = string.Concat(m.Slots.Select(s => $", {s.Type} {s.ParameterName}"));
        w.Line($"public static string GetId(string targetId{parameters}, string userId)");
        w.Line($"    => targetId + \"/{m.PropertyName}Contributions/\"{SlotConcat(m, s => s.ParameterName)}{UserSegment(m)} + userId;");
        w.Line();
        var args = string.Concat(m.Slots.Select(s => $", {s.Name}"));
        w.Line($"string {HasNaturalId}.GetId() => GetId(TargetId{args}, ContributorId);");
        w.Close();
    }

    private static void WriteCurrent(Writer w, ContributionModel m, string access)
    {
        w.Line("/// <summary>");
        w.Line($"/// The current (latest non-hidden) version of <see cref=\"{m.OwnerType}.{m.PropertyName}\"/>{(m.IsCollection ? " for one slot" : "")}:");
        w.Line("/// a cache of one contribution, written in the same transaction, which the library can rebuild. Id:");
        w.Line($"/// <c>{{targetId}}/{m.PropertyName}{(m.IsCollection ? "/" + SlotPath(m).TrimEnd('/') : "")}</c>.");
        w.Line("/// </summary>");
        w.Line("[global::System.CodeDom.Compiler.GeneratedCode(\"MintPlayer.Spark.Contributions.SourceGenerators\", \"1\")]");
        w.Open($"{access} partial class {m.CurrentName} : global::MintPlayer.Spark.Contributions.ICurrentContribution, {HasNaturalId}");

        w.Line("/// <summary>The document id; see <see cref=\"GetId\"/>.</summary>");
        w.Line("public string? Id { get; set; }");
        w.Line();
        w.Line("/// <summary>The document id of the target entity (part of <see cref=\"Id\"/>).</summary>");
        w.Line("public string TargetId { get; set; } = \"\";");
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Line("public string ContributorId { get; set; } = \"\";");
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Line("public string ContributionId { get; set; } = \"\";");
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Line("public global::System.DateTime UpdatedAt { get; set; }");
        if (m.Has(ContributionModel.AttributionHistory))
        {
            w.Line();
            w.Line("/// <summary>How many contributions the slot has (<c>ContributionAttribution.History</c>).</summary>");
            w.Line("public int ContributionCount { get; set; }");
        }
        WriteSlotAndValueProperties(w, m);

        w.Line();
        var path = m.IsCollection ? "/" + SlotPath(m).TrimEnd('/') : "";
        w.Line($"/// <summary><c>{{targetId}}/{m.PropertyName}{path}</c>.</summary>");
        var parameters = string.Concat(m.Slots.Select(s => $", {s.Type} {s.ParameterName}"));
        w.Line($"public static string GetId(string targetId{parameters})");
        w.Line($"    => targetId + \"/{m.PropertyName}{(m.IsCollection ? "/" : "")}\"{SlotConcat(m, s => s.ParameterName)};");
        w.Line();
        var args = string.Concat(m.Slots.Select(s => $", {s.Name}"));
        w.Line($"string {HasNaturalId}.GetId() => GetId(TargetId{args});");
        w.Close();
    }

    private static void WriteSlotAndValueProperties(Writer w, ContributionModel m)
    {
        foreach (var slot in m.Slots)
        {
            w.Line();
            w.Line($"/// <summary>Slot, copied from <see cref=\"{m.Element.FullyQualified}.{slot.Name}\"/>.</summary>");
            w.Line($"public {slot.Type} {slot.Name} {{ get; set; }}{slot.Initializer}");
        }
        foreach (var value in m.Values)
        {
            w.Line();
            w.Line($"/// <summary>Copied from <see cref=\"{m.Element.FullyQualified}.{value.Name}\"/>.</summary>");
            w.Line($"public {value.Type} {value.Name} {{ get; set; }}{value.Initializer}");
        }
    }

    private static void WriteMetadata(Writer w, ContributionModel m, string access)
    {
        var e = m.Element.FullyQualified;
        var c = m.ContributionType;
        var cur = m.CurrentType;
        var baseType = $"global::MintPlayer.Spark.Contributions.ContributionDescriptor<{m.OwnerType}, {e}, {c}, {cur}>";

        w.Line("/// <summary>");
        w.Line($"/// Ids, accessors and mappings for <see cref=\"{m.OwnerType}.{m.PropertyName}\"/>, registered in");
        w.Line("/// <see cref=\"global::MintPlayer.Spark.Contributions.ContributionRegistry\"/> by this assembly's module initializer.");
        w.Line("/// </summary>");
        w.Line("[global::System.CodeDom.Compiler.GeneratedCode(\"MintPlayer.Spark.Contributions.SourceGenerators\", \"1\")]");
        w.Open($"{access} sealed class {m.MetadataName} : {baseType}");

        w.Line("/// <summary>The one instance.</summary>");
        w.Line($"public static {m.MetadataName} Instance {{ get; }} = new();");
        w.Line();
        w.Line($"private {m.MetadataName}() {{ }}");
        w.Line();
        w.Line($"/// <summary>See <see cref=\"global::MintPlayer.Spark.Contributions.ContributionDescriptor.ShapeHash\"/>.</summary>");
        w.Line($"public const string Shape = \"{m.ShapeHash}\";");
        w.Line();
        w.Line($"/// <summary>The generated query over <see cref=\"{c}\"/>.</summary>");
        w.Line($"public const string QueryName = \"{m.QueryName}\";");
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Line($"public override string PropertyName => \"{m.PropertyName}\";");
        w.Line("/// <inheritdoc />");
        w.Line("public override string ContributionsQueryName => QueryName;");
        w.Line("/// <inheritdoc />");
        w.Line($"public override bool IsCollection => {(m.IsCollection ? "true" : "false")};");
        w.Line("/// <inheritdoc />");
        w.Line($"public override global::System.Collections.Generic.IReadOnlyList<string> SlotNames {{ get; }} = {StringArray(m.Slots.Select(s => s.Name))};");
        w.Line("/// <inheritdoc />");
        w.Line($"public override global::System.Collections.Generic.IReadOnlyList<string> ValueNames {{ get; }} = {StringArray(m.Values.Select(v => v.Name))};");
        w.Line("/// <inheritdoc />");
        w.Line($"public override global::MintPlayer.Spark.Contributions.ContributionAttribution Attribution => {AttributionExpression(m.Attribution)};");
        w.Line("/// <inheritdoc />");
        w.Line($"public override global::System.Collections.Generic.IReadOnlyList<string> AttributionAttributeNames {{ get; }} = {StringArray(AttributionNames(m.Attribution))};");
        w.Line("/// <inheritdoc />");
        w.Line($"public override bool IsSoftDeletable => {(m.IsSoftDeletable ? "true" : "false")};");
        w.Line("/// <inheritdoc />");
        w.Line("public override string ShapeHash => Shape;");
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Line($"public override string ContributionPrefix(string targetId) => targetId + \"/{m.PropertyName}Contributions/\";");
        w.Line("/// <inheritdoc />");
        w.Line($"public override string CurrentPrefix(string targetId) => targetId + \"/{m.PropertyName}/\";");
        w.Line();

        // Rows
        w.Line("/// <inheritdoc />");
        w.Open($"public override global::System.Collections.Generic.IReadOnlyList<{e}> GetRows({m.OwnerType} target)");
        if (m.IsCollection)
            w.Line($"return target.{m.PropertyName} is {{ }} rows ? new global::System.Collections.Generic.List<{e}>(rows) : new global::System.Collections.Generic.List<{e}>();");
        else
            w.Line($"return target.{m.PropertyName} is {{ }} row ? new {e}[] {{ row }} : global::System.Array.Empty<{e}>();");
        w.Close();
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Open($"public override void SetRows({m.OwnerType} target, global::System.Collections.Generic.IReadOnlyList<{e}> rows)");
        if (!m.IsCollection)
        {
            w.Line($"target.{m.PropertyName} = rows.Count == 0 ? null! : rows[0];");
        }
        else if (!m.PropertyWritable)
        {
            w.Line($"var held = target.{m.PropertyName};");
            w.Line("held.Clear();");
            w.Line("foreach (var row in rows)");
            w.Line("    held.Add(row);");
        }
        else if (m.Shape == CollectionShape.Array)
        {
            w.Line($"target.{m.PropertyName} = global::System.Linq.Enumerable.ToArray(rows);");
        }
        else
        {
            w.Line($"target.{m.PropertyName} = new global::System.Collections.Generic.List<{e}>(rows);");
        }
        w.Close();
        w.Line();

        // Slots
        w.Line("/// <inheritdoc />");
        w.Line($"public override string SlotKeyOf({e} row) => {SlotKeyExpression(m, "row")};");
        w.Line("/// <inheritdoc />");
        w.Line($"public override string SlotKeyOfContribution({c} contribution) => {SlotKeyExpression(m, "contribution")};");
        w.Line("/// <inheritdoc />");
        w.Line($"public override string SlotKeyOfCurrent({cur} current) => {SlotKeyExpression(m, "current")};");
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Open($"public override string? FindInvalidSlot({e} row)");
        foreach (var slot in m.Slots)
            w.Line($"if (!{Format}.IsValid({slot.Format("row." + slot.Name)})) return \"{slot.Name}\";");
        w.Line("return null;");
        w.Close();
        w.Line();

        // Ids
        var rowSlots = string.Concat(m.Slots.Select(s => $", row.{s.Name}"));
        w.Line("/// <inheritdoc />");
        w.Line($"public override string ContributionId(string targetId, {e} row, string userId) => {c}.GetId(targetId{rowSlots}, userId);");
        w.Line("/// <inheritdoc />");
        w.Line($"public override string CurrentId(string targetId, {e} row) => {cur}.GetId(targetId{rowSlots});");
        w.Line("/// <inheritdoc />");
        w.Line($"public override string SlotContributionPrefix(string targetId, {e} row) => ContributionPrefix(targetId){SlotConcat(m, s => "row." + s.Name)}{UserSegment(m)};");
        w.Line();

        // Mappings
        w.Line("/// <inheritdoc />");
        w.Open($"public override {c} CreateContribution(string targetId, {e} row, string contributorId, global::System.DateTime updatedAtUtc)");
        w.Open($"return new {c}", trailer: "");
        w.Line($"Id = ContributionId(targetId, row, contributorId),");
        w.Line("TargetId = targetId,");
        w.Line("ContributorId = contributorId,");
        w.Line("UpdatedAt = updatedAtUtc,");
        foreach (var slot in m.Slots) w.Line($"{slot.Name} = row.{slot.Name},");
        foreach (var value in m.Values) w.Line($"{value.Name} = row.{value.Name},");
        w.Close(";");
        w.Close();
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Open($"public override void CopyValues({e} row, {c} contribution)");
        foreach (var value in m.Values) w.Line($"contribution.{value.Name} = row.{value.Name};");
        w.Close();
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Open($"public override {cur} CreateCurrent({c} contribution, int contributionCount)");
        var contributionSlots = string.Concat(m.Slots.Select(s => $", contribution.{s.Name}"));
        w.Open($"return new {cur}", trailer: "");
        w.Line($"Id = {cur}.GetId(contribution.TargetId{contributionSlots}),");
        w.Line("TargetId = contribution.TargetId,");
        w.Line("ContributorId = contribution.ContributorId,");
        w.Line($"ContributionId = {c}.GetId(contribution.TargetId{contributionSlots}, contribution.ContributorId),");
        w.Line("UpdatedAt = contribution.UpdatedAt,");
        if (m.Has(ContributionModel.AttributionHistory)) w.Line("ContributionCount = contributionCount,");
        foreach (var slot in m.Slots) w.Line($"{slot.Name} = contribution.{slot.Name},");
        foreach (var value in m.Values) w.Line($"{value.Name} = contribution.{value.Name},");
        w.Close(";");
        w.Close();
        w.Line();
        w.Line("/// <inheritdoc />");
        w.Open($"public override {e} CreateRow({cur} current, string? contributorName)");
        w.Open($"var row = new {e}", trailer: "");
        foreach (var slot in m.Slots) w.Line($"{slot.Name} = current.{slot.Name},");
        foreach (var value in m.Values) w.Line($"{value.Name} = current.{value.Name},");
        w.Close(";");
        if (m.Has(ContributionModel.AttributionContributor)) w.Line("row.__sparkContributorName = contributorName;");
        if (m.Has(ContributionModel.AttributionUpdatedAt)) w.Line("row.__sparkUpdatedAt = current.UpdatedAt;");
        if (m.Has(ContributionModel.AttributionHistory)) w.Line("row.__sparkContributionCount = current.ContributionCount;");
        w.Line("return row;");
        w.Close();

        w.Close();
    }

