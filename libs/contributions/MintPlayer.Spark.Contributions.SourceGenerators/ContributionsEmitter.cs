    /// <summary>
    /// The element's partial: the row key (collections) and the attribution properties, unioned over
    /// every declaration that uses the element, so two targets sharing one element type emit it once.
    /// </summary>
    public static string Element(ElementDeclaration element, IReadOnlyList<SlotModel> slots, int attribution)
    {
        var w = new Writer();
        w.Raw(Header);
        var ns = !string.IsNullOrEmpty(element.Namespace);
        if (ns) w.Open($"namespace {element.Namespace}");
        foreach (var container in element.ContainingDeclarations)
            w.Open(container);
        w.Open(element.Declaration);

        var first = true;
        void Gap() { if (!first) w.Line(); first = false; }

        if (slots.Count > 0)
        {
            Gap();
            w.Line("/// <summary>");
            w.Line($"/// The row key: the slot tuple (<c>{string.Join("/", slots.Select(s => "{" + s.Name + "}"))}</c>), formatted culture-independently.");
            w.Line("/// Deterministic and get-only, so an existing row keeps its identity across loads and saves.");
            w.Line("/// Generated by MintPlayer.Spark.Contributions.");
            w.Line("/// </summary>");
            w.Line("[global::MintPlayer.Spark.Abstractions.ValueKey]");
            w.Line($"public string Key => {SlotKeyExpression(slots, "this")};");
        }

        if ((attribution & ContributionModel.AttributionContributor) != 0)
        {
            Gap();
            w.Line("internal string? __sparkContributorName;");
            w.Line();
            w.Line("/// <summary>Who wrote the current version (read-only; rendering hint <c>contributionAttribution</c>). Resolved at read time, never stored.</summary>");
            w.Line("public string? ContributorName => __sparkContributorName;");
        }
        if ((attribution & ContributionModel.AttributionUpdatedAt) != 0)
        {
            Gap();
            w.Line("internal global::System.DateTime? __sparkUpdatedAt;");
            w.Line();
            w.Line("/// <summary>When the current version was written, in UTC (read-only; rendering hint <c>contributionAttribution</c>).</summary>");
            w.Line("public global::System.DateTime? UpdatedAt => __sparkUpdatedAt;");
        }
        if ((attribution & ContributionModel.AttributionHistory) != 0)
        {
            Gap();
            w.Line("internal int? __sparkContributionCount;");
            w.Line();
            w.Line("/// <summary>How many contributions the slot has (read-only; rendering hint <c>contributionAttribution</c>).</summary>");
            w.Line("public int? ContributionCount => __sparkContributionCount;");
        }

        w.Close();
        foreach (var _ in element.ContainingDeclarations)
            w.Close();
        if (ns) w.Close();
        return w.ToString();
    }

