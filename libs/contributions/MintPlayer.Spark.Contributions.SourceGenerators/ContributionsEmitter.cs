    public static string Registration(string rootNamespace, IReadOnlyList<ContributionModel> models)
    {
        var w = new Writer();
        w.Raw(Header);
        w.Open($"namespace {rootNamespace}");
        w.Line("/// <summary>");
        w.Line("/// Registers this assembly's contribution declarations and their element row keys when the assembly loads.");
        w.Line("/// <c>AddContributions()</c> reads <see cref=\"global::MintPlayer.Spark.Contributions.ContributionRegistry\"/>; nothing is scanned.");
        w.Line("/// </summary>");
        w.Open("internal static class SparkContributionsRegistration");
        w.Line("[global::System.Runtime.CompilerServices.ModuleInitializer]");
        w.Open("internal static void Register()");
        foreach (var element in models.Where(m => m.IsCollection).Select(m => m.Element.FullyQualified).Distinct().OrderBy(x => x, StringComparer.Ordinal))
        {
            w.Line("global::MintPlayer.Spark.Abstractions.Model.SparkValueObjects.Register(" +
                   $"typeof({element}), \"Key\", static o => (({element})o).Key);");
        }
        foreach (var model in models)
            w.Line($"global::MintPlayer.Spark.Contributions.ContributionRegistry.Register({model.MetadataType}.Instance);");
        w.Close();
        w.Close();
        w.Close();
        return w.ToString();
    }

    // ------------------------------------------------------------------ helpers

    private static string SlotPath(ContributionModel m) => string.Concat(m.Slots.Select(s => "{" + s.Name + "}/"));

    /// <summary><c> + Format(a) + "/" + Format(b)</c>; empty without slots.</summary>
    private static string SlotConcat(ContributionModel m, Func<SlotModel, string> expression)
    {
        var sb = new StringBuilder();
        for (var i = 0; i < m.Slots.Length; i++)
        {
            if (i > 0) sb.Append(" + \"/\"");
            sb.Append(" + ").Append(m.Slots[i].Format(expression(m.Slots[i])));
        }
        return sb.ToString();
    }

    /// <summary>The user segment after the slots: <c>"/User/"</c>, or <c>"User/"</c> straight after the prefix's slash when there are none.</summary>
    private static string UserSegment(ContributionModel m) => m.Slots.Length > 0 ? " + \"/User/\"" : " + \"User/\"";

    private static string SlotKeyExpression(ContributionModel m, string owner) => SlotKeyExpression(m.Slots.ToList(), owner);

    private static string SlotKeyExpression(IReadOnlyList<SlotModel> slots, string owner)
        => slots.Count == 0
            ? "\"\""
            : string.Join(" + \"/\" + ", slots.Select(s => s.Format($"{owner}.{s.Name}")));

    private static string StringArray(IEnumerable<string> items)
    {
        var list = items.ToList();
        return list.Count == 0
            ? "global::System.Array.Empty<string>()"
            : "new string[] { " + string.Join(", ", list.Select(i => "\"" + i + "\"")) + " }";
    }

    private static IEnumerable<string> AttributionNames(int attribution)
    {
        if ((attribution & ContributionModel.AttributionContributor) != 0) yield return "ContributorName";
        if ((attribution & ContributionModel.AttributionUpdatedAt) != 0) yield return "UpdatedAt";
        if ((attribution & ContributionModel.AttributionHistory) != 0) yield return "ContributionCount";
    }

    private static string AttributionExpression(int attribution)
    {
        const string type = "global::MintPlayer.Spark.Contributions.ContributionAttribution";
        var parts = new List<string>();
        if ((attribution & ContributionModel.AttributionContributor) != 0) parts.Add(type + ".Contributor");
        if ((attribution & ContributionModel.AttributionUpdatedAt) != 0) parts.Add(type + ".UpdatedAt");
        if ((attribution & ContributionModel.AttributionHistory) != 0) parts.Add(type + ".History");
        return parts.Count == 0 ? type + ".None" : string.Join(" | ", parts);
    }

    /// <summary>A minimal indented writer with <c>\n</c> line endings, so snapshots don't depend on the OS.</summary>
    private sealed class Writer
    {
        private readonly StringBuilder sb = new();
        private readonly Stack<string> trailers = new();
        private int indent;

        public void Raw(string text) => sb.Append(text).Append('\n');

        public void Line(string text = "")
        {
            if (text.Length > 0)
                sb.Append(' ', indent * 4).Append(text);
            sb.Append('\n');
        }

        public void Open(string header, string trailer = "")
        {
            Line(header);
            Line("{");
            indent++;
            trailers.Push(trailer);
        }

        public void Close(string? suffix = null)
        {
            indent--;
            var trailer = trailers.Pop();
            Line("}" + (suffix ?? trailer));
        }

        public override string ToString() => sb.ToString();
    }
