namespace MintPlayer.Spark.Abstractions;

/// <summary>
/// A stored file: the value of a <c>BinaryFile</c> attribute (#700). Declare a property of this type
/// (or <c>List&lt;SparkFile&gt;</c>) and the model gets <c>dataType: "BinaryFile"</c>.
/// </summary>
/// <remarks>
/// <para>
/// Every member is <b>written by the server</b>. A save never copies a client-sent <see cref="SparkFile"/>
/// into the entity: the client either echoes a stored value back (kept as it is, matched by
/// <see cref="FileId"/>), claims a fresh upload with its upload token, or sends <see langword="null"/> to
/// clear. A forged <see cref="FileId"/> that the entity does not already hold is refused, so a client
/// cannot point an attribute at someone else's bytes.
/// </para>
/// <para>
/// The bytes are not here. They live in the configured file store (<c>MintPlayer.Spark.Files</c>), keyed
/// by <see cref="FileId"/>. On the wire, a read response adds a short-lived <c>url</c> to each file the
/// caller may read; that url is never stored.
/// </para>
/// </remarks>
public class SparkFile
{
    /// <summary>The store key, generated by the server. Never derived from the client's file name.</summary>
    public string FileId { get; set; } = string.Empty;

    /// <summary>The client's file name, sanitised (normalised, control and path characters removed, length capped). Display only.</summary>
    public string FileName { get; set; } = string.Empty;

    /// <summary>The content type the server detected from the bytes (magic numbers), never the one the client claimed.</summary>
    public string ContentType { get; set; } = string.Empty;

    /// <summary>Length in bytes.</summary>
    public long Length { get; set; }

    /// <summary>Lowercase hex SHA-256 of the stored bytes. Also the download ETag.</summary>
    public string? Sha256 { get; set; }

    /// <summary>The malware scan's verdict. Only <see cref="SparkFileScanStatus.Clean"/> files are served.</summary>
    public SparkFileScanStatus ScanStatus { get; set; }

    /// <summary>When the upload was committed (UTC).</summary>
    public DateTimeOffset UploadedAt { get; set; }

    /// <summary>The id of the user who uploaded it, or <see langword="null"/> for an anonymous or system upload.</summary>
    public string? UploadedBy { get; set; }
}

/// <summary>
/// A stored raster image: the value of an <c>Image</c> attribute (#700). The bytes were decoded and
/// re-encoded on upload, which applied the EXIF orientation and dropped all metadata.
/// </summary>
public class SparkImage : SparkFile
{
    /// <summary>Width in pixels, after orientation.</summary>
    public int Width { get; set; }

    /// <summary>Height in pixels, after orientation.</summary>
    public int Height { get; set; }

    /// <summary>The downscaled copies made on upload, by variant name (<c>thumb</c>, <c>medium</c>, …). Empty when variants are off.</summary>
    public Dictionary<string, SparkImageVariant> Variants { get; set; } = new(StringComparer.Ordinal);
}

/// <summary>One downscaled copy of a <see cref="SparkImage"/>.</summary>
public class SparkImageVariant
{
    /// <summary>The variant's own store key.</summary>
    public string FileId { get; set; } = string.Empty;

    /// <summary>The encoded content type (e.g. <c>image/webp</c>).</summary>
    public string ContentType { get; set; } = string.Empty;

    /// <summary>Width in pixels.</summary>
    public int Width { get; set; }

    /// <summary>Height in pixels.</summary>
    public int Height { get; set; }

    /// <summary>Length in bytes.</summary>
    public long Length { get; set; }
}

/// <summary>The malware scan state of a <see cref="SparkFile"/>. Fail-closed: only <see cref="Clean"/> is claimable or served.</summary>
public enum SparkFileScanStatus
{
    /// <summary>Not scanned yet (deferred scanning).</summary>
    Pending = 0,

    /// <summary>The scanner reported no known malware, or the app explicitly runs without a scanner.</summary>
    Clean = 1,

    /// <summary>The scanner reported malware. The bytes are deleted.</summary>
    Infected = 2,

    /// <summary>The scanner failed (unreachable, timeout, an unreadable reply). Treated as not clean.</summary>
    ScanFailed = 3,
}
