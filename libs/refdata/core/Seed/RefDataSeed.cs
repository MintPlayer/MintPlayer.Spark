namespace MintPlayer.Spark.ReferenceData.Seed;

/// <summary>
/// The basic seed set (RD9 = commerce D39, PRD §3.2): every adapter's real fixture run through the same pipeline and
/// ledgers, written as a release whose id is <see cref="Release"/>. It is test data, not a coverage tier: full imports
/// stay manual local runs (RD2). The committed copy is regenerated by <c>--refdata-build-seed</c> and checked by
/// <c>--refdata-verify-seed</c> (exit 3 on drift), which CI runs.
/// </summary>
public static class RefDataSeed
{
    /// <summary>The seed's release id: <c>Release.Introduced</c>/<c>Changed</c> of every document it wrote.</summary>
    public const string Release = "seed";

    public const string BuildFlag = "--refdata-build-seed";
    public const string VerifyFlag = "--refdata-verify-seed";

    /// <summary>The seed's documents and manifest, stamped with <see cref="Release"/>.</summary>
    public static async Task<(ReleaseManifest Manifest, IReadOnlyList<object> Documents, RefDataBuild Build)> BuildAsync(RefDatasetBuilder builder, CancellationToken cancellationToken)
    {
        var build = await builder.BuildFixturesAsync(cancellationToken);
        var documents = build.Documents().ToList();
        foreach (var document in documents)
            document.GetType().GetProperty("Release")!.SetValue(document, new ReleaseStamp { Introduced = Release, Changed = Release });
        var manifest = new ReleaseManifest
        {
            Release = Release,
            Builder = "MintPlayer.Spark.ReferenceData seed",
            KeyVersion = RefSearchKeys.KeyVersion,
            Sources = [.. build.Sources.Values],
            NextEffectiveDate = null,
        };
        return (manifest, documents, build);
    }

    /// <summary>
    /// Handles <c>--refdata-build-seed</c> (writes the seed release, and the ids it had to mint under <c>ledger-added/</c>) and <c>--refdata-verify-seed</c> (writes nothing; exit 3 when the committed seed or ledgers differ
    /// from what the fixtures build). Needs no database. Returns <see langword="true"/> when a command ran.
    /// </summary>
    public static bool RunReferenceDataSeedCommandIfRequested(this WebApplication app, string[] args)
    {
        var build = args.Contains(BuildFlag);
        var verify = args.Contains(VerifyFlag);
        if (!build && !verify)
            return false;

        var options = app.Services.GetRequiredService<IOptions<SparkReferenceDataOptions>>().Value;
        var directory = Path.GetFullPath(Path.Combine(app.Environment.ContentRootPath, options.Seed.Directory));
        var builder = app.Services.GetRequiredService<RefDatasetBuilder>();
        var (manifest, documents, dataset) = BuildAsync(builder, CancellationToken.None).GetAwaiter().GetResult();

        var memory = new MemoryReleaseFileStore();
        ReleaseWriter.WriteAsync(memory, manifest, documents, CancellationToken.None).GetAwaiter().GetResult();
        if (build)
        {
            var disk = new DirectoryReleaseFileStore(directory);
            foreach (var (path, bytes) in memory.Files)
                disk.WriteAsync(path, bytes, CancellationToken.None).GetAwaiter().GetResult();
            // Ids minted now (not yet in an adapter's shipped ledger): written beside the seed, to be moved into the
            // adapters' Ledger/{cc}.ndjson. The verify refuses a seed while any remain.
            var pending = Path.Combine(directory, "ledger-added");
            if (Directory.Exists(pending)) Directory.Delete(pending, recursive: true);
            foreach (var (country, lines) in LedgerFiles(dataset.Ledger.Added))
                disk.WriteAsync($"ledger-added/{country}.ndjson", Encoding.UTF8.GetBytes(lines), CancellationToken.None).GetAwaiter().GetResult();
            Console.WriteLine($"Reference-data seed written to {directory}: {documents.Count} documents, {dataset.Ledger.Added.Count} ledger lines minted.");
            if (dataset.Ledger.Added.Count > 0)
                Console.WriteLine("Append ledger-added/{cc}.ndjson to the adapters' Ledger/{cc}.ndjson (sorted by identity) so independent instances mint the same ids (Q-R5), rebuild, and run this again.");
            foreach (var warning in dataset.Warnings)
                Console.WriteLine("warning: " + warning);
            Environment.ExitCode = 0;
            return true;
        }

        var drift = new List<string>();
        foreach (var (path, bytes) in memory.Files)
        {
            var full = Path.Combine(directory, path.Replace('/', Path.DirectorySeparatorChar));
            if (!File.Exists(full)) drift.Add($"{path}: missing");
            else if (!File.ReadAllBytes(full).AsSpan().SequenceEqual(bytes)) drift.Add($"{path}: differs");
        }
        if (dataset.Ledger.Added.Count > 0)
            drift.Add($"{dataset.Ledger.Added.Count} ids are not in the adapters' shipped ledgers (first: {dataset.Ledger.Added[0].Identity} → {dataset.Ledger.Added[0].Id})");
        if (drift.Count > 0)
        {
            Console.Error.WriteLine($"The reference-data seed in {directory} is stale; run {BuildFlag} and commit:");
            foreach (var line in drift) Console.Error.WriteLine("  " + line);
            Environment.ExitCode = 3;
        }
        else
        {
            Console.WriteLine("The reference-data seed is up to date.");
            Environment.ExitCode = 0;
        }
        return true;
    }

    /// <summary>Ledger lines, one ndjson text per country (sorted by identity), in the adapters' <c>Ledger/</c> format.</summary>
    public static IEnumerable<(string Country, string Lines)> LedgerFiles(IEnumerable<LedgerEntry> entries)
        => entries.OrderBy(e => e.Identity, StringComparer.Ordinal)
            .GroupBy(e => RefIds.CountryOf(e.Id) ?? "_")
            .OrderBy(g => g.Key, StringComparer.Ordinal)
            .Select(g => (g.Key, string.Concat(g.Select(e => System.Text.Json.JsonSerializer.Serialize(e, LedgerJson.Options) + "\n"))));
}

/// <summary>An in-memory <see cref="IReleaseFileStore"/>.</summary>
public sealed class MemoryReleaseFileStore : IReleaseFileStore
{
    public SortedDictionary<string, byte[]> Files { get; } = new(StringComparer.Ordinal);

    public Task<byte[]?> ReadAsync(string path, CancellationToken cancellationToken)
        => Task.FromResult(Files.TryGetValue(path, out var bytes) ? bytes : null);

    public Task WriteAsync(string path, byte[] bytes, CancellationToken cancellationToken)
    {
        Files[path] = bytes;
        return Task.CompletedTask;
    }
}

/// <summary>
/// Applies the committed seed release once the host has started (RD9): a fresh database gets the basic set, a second
/// start writes nothing (every hash matches), and a document a full import wrote since is never touched
/// (<see cref="ReleaseOverwrite.OnlySeedOwned"/>). Writes are optimistic per chunk and retried on a concurrent write.
/// </summary>
internal sealed class RefDataSeeder(
    IDocumentStore store,
    IOptions<SparkReferenceDataOptions> options,
    IHostEnvironment environment,
    ILogger<RefDataSeeder> logger) : IHostedLifecycleService
{
    public async Task StartedAsync(CancellationToken cancellationToken)
    {
        if (!options.Value.Seed.Enabled)
            return;
        var directory = Path.GetFullPath(Path.Combine(environment.ContentRootPath, options.Value.Seed.Directory));
        if (!File.Exists(Path.Combine(directory, ReleaseFormat.ManifestFile)))
        {
            logger.LogWarning("Reference data: no seed release in {Directory}; run {Flag} to write one.", directory, RefDataSeed.BuildFlag);
            return;
        }
        for (var attempt = 1; ; attempt++)
        {
            try
            {
                var result = await SeedAsync(store, new DirectoryReleaseFileStore(directory), cancellationToken);
                if (result.Written > 0)
                    logger.LogInformation("Reference data seed: {Added} added, {Updated} refreshed, {Skipped} unchanged.", result.Added, result.Updated, result.Skipped);
                return;
            }
            catch (ConcurrencyException) when (attempt < 3)
            {
            }
        }
    }

    /// <summary>One pass: read and verify the seed release, then apply it seed-owned only.</summary>
    internal static async Task<ReleaseApplyResult> SeedAsync(IDocumentStore store, IReleaseFileStore files, CancellationToken cancellationToken)
    {
        var release = await ReleaseReader.ReadAsync(files, cancellationToken);
        return await ReleaseApplier.ApplyAsync(store, release, ReleaseOverwrite.OnlySeedOwned, cancellationToken);
    }

    public Task StartingAsync(CancellationToken cancellationToken) => Task.CompletedTask;
    public Task StartAsync(CancellationToken cancellationToken) => Task.CompletedTask;
    public Task StopAsync(CancellationToken cancellationToken) => Task.CompletedTask;
    public Task StoppingAsync(CancellationToken cancellationToken) => Task.CompletedTask;
    public Task StoppedAsync(CancellationToken cancellationToken) => Task.CompletedTask;
}
