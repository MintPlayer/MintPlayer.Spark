#!/usr/bin/env node
// Generates libs/gs1/MintPlayer.Spark.Gs1/pg/aitable.pg, the AI dictionary as Polyglot data, from GS1's Barcode
// Syntax Dictionary (tools/gs1/gs1-syntax-dictionary.txt, Apache-2.0, https://github.com/gs1/gs1-syntax-dictionary,
// commit c63d8a12210d). Polyglot then emits it as C# (MintPlayer.Spark.Gs1) and TypeScript (ng-spark/scanning),
// so both parsers read one table (warehouse Q-W16).
//
// Usage: node tools/gs1/generate-ai-table.mjs   (then refresh the TS copy: polyglot build --only typescript)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.join(here, 'gs1-syntax-dictionary.txt');
const target = path.resolve(here, '../../libs/gs1/MintPlayer.Spark.Gs1/pg/aitable.pg');

// A component: `N6`, `X..20`, `N14,csum,gcppos2`; optional ones are bracketed, `[X..17]` or `[N2],mi`.
const component = /^(\[)?([NXYZ])(\d*)(\.\.(\d+))?(\])?((?:,[a-z0-9]+)*)(\])?$/;
const pgString = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';

const entries = [];
for (const line of fs.readFileSync(source, 'utf8').split(/\r?\n/)) {
  if (!line.trim() || line.startsWith('#')) continue;
  const hash = line.indexOf('#');
  const title = hash >= 0 ? line.slice(hash + 1).trim() : '';
  const tokens = (hash >= 0 ? line.slice(0, hash) : line).trim().split(/\s+/);
  const [first, last = first] = tokens.shift().split('-');
  const flags = tokens.length && !component.test(tokens[0]) ? tokens.shift() : '';
  const components = [];
  while (tokens.length && component.test(tokens[0])) {
    const [, open, charset, fixed, range, max, closeBeforeLinters, linters, closeAtEnd] = component.exec(tokens.shift());
    if (Boolean(open) !== Boolean(closeBeforeLinters || closeAtEnd)) throw new Error(`unbalanced optional component in: ${line}`);
    const min = range ? (fixed ? Number(fixed) : 1) : Number(fixed);
    components.push({ charset, min, max: range ? Number(max) : min, optional: Boolean(open), linters: linters.slice(1) });
  }
  if (!components.length) throw new Error(`no specification in: ${line}`);
  entries.push({ first, last, predefined: flags.includes('*'), dlAttribute: flags.includes('?'), components, attributes: tokens.join(' '), title });
}

const rows = entries.map((e) => {
  const comps = e.components
    .map((c) => `Gs1Component(${pgString(c.charset)}, ${c.min}, ${c.max}, ${c.optional}, ${pgString(c.linters)})`)
    .join(', ');
  return `    Gs1AiEntry(${pgString(e.first)}, ${pgString(e.last)}, ${e.predefined}, ${e.dlAttribute}, [${comps}], ${pgString(e.attributes)}, ${pgString(e.title)})`;
});

const pg = `// Generated by tools/gs1/generate-ai-table.mjs from GS1's Barcode Syntax Dictionary. Do not edit.
// Source: tools/gs1/gs1-syntax-dictionary.txt (Apache-2.0, https://github.com/gs1/gs1-syntax-dictionary).
import "std.collections"

// One component of an AI's data field: its character set (N numeric, X CSET 82, Y CSET 39, Z base64url), its length
// range, whether it is optional, and the comma-separated linters that validate it.
record Gs1Component(charset: string, minLength: i32, maxLength: i32, optional: bool, linters: string)

// One dictionary entry: an AI or an AI range (first..last), whether its length is predefined (no FNC1 after it),
// whether it may be a Digital Link data attribute, its components, its attributes (req=, ex=, dlpkey) and its title.
record Gs1AiEntry(first: string, last: string, predefinedLength: bool, dlDataAttribute: bool, components: List<Gs1Component>, attributes: string, title: string)

fn gs1AiTable(): List<Gs1AiEntry> {
  return [
${rows.join(',\n')}
  ]
}
`;
fs.writeFileSync(target, pg);
console.log(`wrote ${path.relative(process.cwd(), target)}: ${entries.length} entries`);
