namespace CodeCoverage.Git.MergeQueue;

/// <summary>One rule a preset or a default adds to <c>autoResolve</c>; <see cref="Regenerate"/> null leaves it to the
/// strategy's default (O36).</summary>
public sealed record AutoResolvePresetRule(string Path, string Strategy, IReadOnlyList<string> Validate, bool? Regenerate = null);

/// <summary>
/// The named rule sets of <c>coverage.yml</c> (docs/coverage_merge_queue_PRD.md §10.3, O35, O36), expanded by the app's
/// parser after the repository's explicit rules, so an explicit rule (<c>strategy: evict</c> among them) always wins for
/// its path. Shared with the git writer's tests so the parser and the writer read one list.
/// </summary>
public static class AutoResolvePresets
{
    private static readonly string[] None = [];

    /// <summary>
    /// <c>autoResolveDefaults: [...]</c>: opt-in take-base presets for generated files, each regenerated by the workflow
    /// (§10.2). Lockfiles are rebuilt by their tool, never text-merged.
    /// </summary>
    public static IReadOnlyDictionary<string, IReadOnlyList<AutoResolvePresetRule>> Presets { get; } = new Dictionary<string, IReadOnlyList<AutoResolvePresetRule>>(StringComparer.Ordinal)
    {
        ["spark"] =
        [
            new("**/App_Data/modelHashes.json", MergeQueueWireRules.TakeBase, None, true),
            new("**/App_Data/securityPosture.txt", MergeQueueWireRules.TakeBase, None, true),
        ],
        ["npm"] =
        [
            new("**/package-lock.json", MergeQueueWireRules.TakeBase, None, true),
            new("**/npm-shrinkwrap.json", MergeQueueWireRules.TakeBase, None, true),
        ],
        ["pnpm"] = [new("**/pnpm-lock.yaml", MergeQueueWireRules.TakeBase, None, true)],
        ["yarn"] = [new("**/yarn.lock", MergeQueueWireRules.TakeBase, None, true)],
        ["nuget"] = [new("**/packages.lock.json", MergeQueueWireRules.TakeBase, None, true)],
    };

    /// <summary>
    /// <c>keepBothDefaults</c>: the keep-both rules every queue-enabled repository gets unless its <c>coverage.yml</c>
    /// turns them off (O35 #1, O36 #1), each group on by default. Appended after the explicit rules and the presets.
    /// </summary>
    public static IReadOnlyDictionary<string, IReadOnlyList<AutoResolvePresetRule>> KeepBothDefaults { get; } = new Dictionary<string, IReadOnlyList<AutoResolvePresetRule>>(StringComparer.Ordinal)
    {
        ["json"] = [new("**/*.json", MergeQueueWireRules.KeepBoth, [MergeQueueWireRules.JsonNoDuplicateKeys])],
        ["ignoreFiles"] =
        [
            new("**/.gitignore", MergeQueueWireRules.KeepBoth, [MergeQueueWireRules.Utf8]),
            new("**/.dockerignore", MergeQueueWireRules.KeepBoth, [MergeQueueWireRules.Utf8]),
            new("**/.prettierignore", MergeQueueWireRules.KeepBoth, [MergeQueueWireRules.Utf8]),
            new("**/.eslintignore", MergeQueueWireRules.KeepBoth, [MergeQueueWireRules.Utf8]),
        ],
        ["changelog"] = [new("**/CHANGELOG.md", MergeQueueWireRules.KeepBoth, [MergeQueueWireRules.Utf8])],
        ["xmlProjects"] =
        [
            new("**/*.csproj", MergeQueueWireRules.KeepBoth, [MergeQueueWireRules.Xml]),
            new("**/Directory.Packages.props", MergeQueueWireRules.KeepBoth, [MergeQueueWireRules.Xml]),
            new("**/*.props", MergeQueueWireRules.KeepBoth, [MergeQueueWireRules.Xml]),
            new("**/*.targets", MergeQueueWireRules.KeepBoth, [MergeQueueWireRules.Xml]),
        ],
    };

    /// <summary>The order the keep-both default groups are appended in.</summary>
    public static IReadOnlyList<string> KeepBothDefaultOrder { get; } = ["json", "ignoreFiles", "changelog", "xmlProjects"];

    /// <summary>
    /// The <c>regeneratedPaths</c> a repository gets when its <c>coverage.yml</c> does not set the key (O37): the files a
    /// regenerate workflow typically rewrites, Spark's generated files and the lockfiles. A <c>regeneratedPaths</c> in
    /// <c>coverage.yml</c>, even an empty one, replaces this list entirely; it is never merged into it.
    /// </summary>
    public static IReadOnlyList<string> DefaultRegeneratedPaths { get; } =
    [
        "**/App_Data/modelHashes.json",
        "**/App_Data/securityPosture.txt",
        "**/package-lock.json",
        "**/npm-shrinkwrap.json",
        "**/yarn.lock",
        "**/pnpm-lock.yaml",
        "**/packages.lock.json",
    ];
}
